<script>
  // On page load, initialize the view
  window.addEventListener('DOMContentLoaded', () => {
    const toggleButtons = document.querySelectorAll('.toggle-btn');
    const toggleContents = document.querySelectorAll('.toggle-content');

    // Set the first button active
    if (toggleButtons.length > 0) {
      toggleButtons.forEach(btn => btn.classList.remove('active'));
      toggleButtons[0].classList.add('active');
    }

    // Show first content only, hide others
    if (toggleContents.length > 0) {
      toggleContents.forEach(content => content.style.display = 'none');
      toggleContents[0].style.display = 'block';
    }

    // Also hide all full-blog-content initially
    document.querySelectorAll('.full-blog-content').forEach(el => el.style.display = 'none');
  });

  // Toggle between cadet and military
  document.querySelectorAll('.toggle-btn').forEach(btn => {
    btn.addEventListener('click', function () {
      document.querySelectorAll('.toggle-btn').forEach(b => b.classList.remove('active'));
      this.classList.add('active');

      const target = this.getAttribute('data-target');
      document.querySelectorAll('.toggle-content').forEach(content => {
        content.style.display = content.id === target ? 'block' : 'none';
      });

      // Hide detail sections when switching
      document.querySelectorAll('.full-blog-content').forEach(el => el.style.display = 'none');
    });
  });

  // Read more functionality
  document.querySelectorAll('.read-more-btn').forEach(button => {
    button.addEventListener('click', function () {
      const blogId = this.getAttribute('data-blog');
      const blogDetail = document.getElementById(blogId);
      blogDetail.style.display = blogDetail.style.display === 'none' ? 'block' : 'none';
      this.innerHTML = blogDetail.style.display === 'block' 
        ? '<i class="far fa-angle-up"></i> Show Less' 
        : '<i class="far fa-angle-right"></i> Read More';
    });
  });
</script>





  
